/**
 * Scheme rule schema (rules-as-data). Workflow A drafts must validate against this.
 */
import { z } from "zod";
import { I18nZ } from "@kisansahay/contracts";

export const OpZ = z.enum([
  "eq", "ne", "gt", "gte", "lt", "lte", "in", "not_in", "intersects", "exists", "not_exists",
]);
export type Op = z.infer<typeof OpZ>;

export const ConditionZ = z.object({
  field: z.string(),
  op: OpZ,
  value: z.unknown().optional(),
  soft: z.boolean().optional(),
  label: I18nZ.optional(),
  source_page: z.number().optional(),
  source_quote: z.string().optional(),
});
export type Condition = z.infer<typeof ConditionZ>;

export const DeadlineRuleZ = z.object({
  id: z.string(),
  kind: z.enum(["after_event", "season_cutoff", "fixed"]),
  field: z.string().optional(),
  hours: z.number().optional(),
  applies_if: ConditionZ.optional(),
  season_field: z.string().optional(),
  dates: z.record(z.string()).optional(),
  due_at: z.string().optional(),
  label: z.string(),
});
export type DeadlineRule = z.infer<typeof DeadlineRuleZ>;

const RelZ = z.object({ id: z.string(), note: I18nZ });

export const SchemeRuleZ = z.object({
  id: z.string().regex(/^[a-z0-9_]+$/),
  state: z.string().optional(),
  name: I18nZ,
  benefit_summary: I18nZ,
  source: z.object({ url: z.string(), verified_on: z.string() }),
  review_status: z.string(),
  relevant_pain_points: z.array(z.string()).default([]),
  eligibility: z.object({
    all: z.array(ConditionZ).optional(),
    any: z.array(ConditionZ).optional(),
  }),
  priority_if: z.array(ConditionZ).optional(),
  local_checks: z.array(I18nZ).optional(),
  documents: z.array(z.string()),
  stacks_with: z.array(RelZ).default([]),
  conflicts_with: z.array(RelZ).default([]),
  requires: z.array(RelZ).default([]),
  deadline_rules: z.array(DeadlineRuleZ).default([]),
  action: z.object({
    label: I18nZ,
    kind: z.enum(["do_now", "collect_doc", "visit", "call", "wait", "info"]),
    link: z.string().optional(),
  }),
  stuck_payment_checks: z.array(z.object({
    id: z.string(), field: z.string(), expect: z.unknown(), label: I18nZ, fix: I18nZ,
  })).optional(),
});
export type SchemeRule = z.infer<typeof SchemeRuleZ>;

/** A rule test case: profile fragment + expected verdict (generated by Workflow A from circular examples). */
export const RuleTestZ = z.object({
  name: z.string(),
  profile: z.record(z.unknown()),
  expect: z.enum(["eligible", "likely", "needs_info", "not_eligible"]),
  source_quote: z.string().optional(),
});
export type RuleTest = z.infer<typeof RuleTestZ>;
